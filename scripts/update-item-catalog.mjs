// Refresh the offline catalog from PUBLIC game metadata, never from a player ZIP.
import {writeFile} from 'node:fs/promises';
import {itemNameKey} from '../site/lib/item-name-key.mjs';

const base='https://valorant-api.com/v1/';
const groups=[['weapons/skins',['levels','chromas']],['sprays',['levels']],['buddies',['levels']],
  ['playercards',[]],['playertitles',[]],['agents',[]],['bundles',[]],['flex',[]]];
const compare=(a,b)=>a<b?-1:a>b?1:0;
async function get(resource){
  const r=await fetch(base+resource,{signal:AbortSignal.timeout(30_000)});
  if(!r.ok)throw Error(`${resource}: HTTP ${r.status}`);
  const {data}=await r.json();
  if(!data)throw Error(`${resource}: missing data`);
  return data;
}
const version=await get('version');
const names=new Map();
function add(en,ja){
  if(typeof en!=='string'||typeof ja!=='string'||!en.trim()||!ja.trim()||en===ja)return;
  const key=itemNameKey(en);
  if(!key)return;
  if(!names.has(key))names.set(key,new Set());
  names.get(key).add(ja);
}
for(const [section,children] of groups){
  function records(data){
    if(!Array.isArray(data)||!data.length)throw Error(`${section}: empty catalog`);
    return data.flatMap(row=>[row,...children.flatMap(key=>row[key]??[])]);
  }
  const [en,ja]=await Promise.all([get(`${section}?language=en-US`),get(`${section}?language=ja-JP`)]);
  const translations=new Map(records(ja).map(row=>[row.uuid,row]));
  for(const row of records(en)){
    const local=translations.get(row.uuid);
    if(!local)continue;
    add(row.displayName,local.displayName);
    if(section==='bundles'&&row.displayName&&local.displayName){
      for(const suffix of [' Bundle',' Collection'])add(row.displayName+suffix,`${local.displayName} セット`);
    }
  }
}
const pairs=[...names].filter(([,vals])=>vals.size===1).map(([k,vals])=>[k,vals.values().next().value]).sort(([a],[b])=>compare(a,b));
if(pairs.length<1000||typeof version.version!=='string')throw Error('Unexpectedly small catalog or missing catalog version');
const data=JSON.stringify(pairs).replaceAll('],[','],\n[');
await writeFile(new URL('../site/lib/item-catalog.mjs',import.meta.url),`// Generated by scripts/update-item-catalog.mjs. Public name pairs only.\n// Source: https://valorant-api.com/ (unofficial). VALORANT names: Riot Games.\nexport const itemCatalogVersion = ${JSON.stringify(version.version)};\nexport const itemCatalog = new Map(${data});\n`);
console.log(`Generated ${pairs.length} public Japanese name mappings (${version.version}).`);
