import {readFile,writeFile} from 'node:fs/promises';
import {Script} from 'node:vm';

// The two owned library files are import-free. Wrap them separately to produce
// one self-contained asset; this enables offline worker restarts via Blob URLs.
const files = [
  ['zipLib','../site/lib/zip.mjs',['readZip']],
  ['dataLib','../site/lib/data.mjs',['PATHS','normalizeCategory']],
];
const load = path => readFile(new URL(path,import.meta.url),'utf8');
const scopes = await Promise.all(files.map(async ([scope,path,exposed]) => {
  const source = await load(path);
  if (/^\s*import\s/m.test(source))throw Error(`${path} must not use imports`);
  const exported = [...source.matchAll(/^export\s+(?:async\s+)?(?:const|let|function|class)\s+(\w+)/gm)].map(m=>m[1]);
  if (!exposed.every(name=>exported.includes(name)))throw Error(`Missing contract export in ${path}`);
  const body = source.replace(/^export\s+(?=(?:async\s+)?(?:const|let|function|class)\s)/gm,'');
  return `const ${scope} = (() => {\n${body}\nreturn {${exposed.join(',')}};\n})();\n`;
}));
const generated = `// Generated by node scripts/build-worker.mjs; edit the source modules instead.\n'use strict';\n${scopes.join('\n')}\n${await load('./worker-core.mjs')}`;
new Script(generated,{filename:'zip-worker.mjs'});
const target = new URL('../site/zip-worker.mjs',import.meta.url);
if(process.argv.includes('--check')){
  if(await readFile(target,'utf8')!==generated)throw Error('Worker is out of date. Run npm run build.');
}else await writeFile(target,generated);
